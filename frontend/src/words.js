// 统一写法：小写、弯撇号转直撇号、去掉句末标点、压缩空格。
// 课程里的词首字母常大写（"Hello"），也会带 "Let's" 这种撇号。
export function normalizeWord(text) {
  return String(text || '')
    .trim()
    .toLowerCase()
    .replace(/[’‘`]/g, "'")
    .replace(/[^a-z' ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// 查词：命中返回 { ipa, cn }，没收录返回 null（界面就不显示这一行）
export function lookupWord(text) {
  const hit = WORDS[normalizeWord(text)];
  if (!hit) return null;
  return { ipa: hit[0], cn: hit[1] };
}
